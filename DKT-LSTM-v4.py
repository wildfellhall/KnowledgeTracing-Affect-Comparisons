# Check the packaging checksum, then unpack source without path traversal/symlinks.
archive = base64.b64decode(PACKAGE_B64)
if hashlib.sha256(archive).hexdigest() != PACKAGE_SHA256:
    raise RuntimeError("Embedded package checksum mismatch; obtain an intact notebook.")
source_dir = Path("/content/dkt_temporal_affect_v4") / PACKAGE_SHA256[:12]
source_dir.mkdir(parents=True, exist_ok=True)
with zipfile.ZipFile(io.BytesIO(archive)) as z:
    for member in z.infolist():
        rel = Path(member.filename)
        if rel.is_absolute() or ".." in rel.parts or stat.S_ISLNK(member.external_attr >> 16):
            raise RuntimeError("Unsafe package member: " + member.filename)
        dest = source_dir / rel
        if member.is_dir():
            dest.mkdir(parents=True, exist_ok=True)
            continue
        content = z.read(member)
        if dest.exists() and dest.read_bytes() != content:
            raise RuntimeError(f"Materialized source was changed: {dest}. Preserve it and use a fresh runtime; do not mix experiments.")
        dest.parent.mkdir(parents=True, exist_ok=True)
        if not dest.exists():
            dest.write_bytes(content)

