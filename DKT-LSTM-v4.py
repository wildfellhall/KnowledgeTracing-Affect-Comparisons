def run_stage(label, argv):
    print("\n" + "=" * 88 + "\n" + label + "\n" + "=" * 88, flush=True)
    env = dict(os.environ)
    env.setdefault("PYTHONUNBUFFERED", "1")
    env.setdefault("OMP_NUM_THREADS", "4")
    env.setdefault("OPENBLAS_NUM_THREADS", "4")
    with log_path.open("a", encoding="utf-8") as log:
        log.write("\n" + label + "\n" + " ".join(argv) + "\n")
        log.flush()
        process = subprocess.Popen(argv, cwd=str(source_dir), env=env,
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, bufsize=1)
        try:
            for line in process.stdout:
                print(line, end="", flush=True)
                log.write(line); log.flush()
            return_code = process.wait()
        except BaseException:
            process.terminate()
            try:
                process.wait(timeout=15)
            except subprocess.TimeoutExpired:
                process.kill(); process.wait()
            raise
    if return_code:
        raise RuntimeError(f"{label} failed (exit {return_code}); the actual traceback is above and in {log_path}.")

